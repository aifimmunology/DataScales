"""Run-2 written report: results/{runs,setup}.parquet + results/metrics/*.parquet -> report/report.md.

Interactive version: report/compare_run2.html (41_compare_data.py, 42_build_compare.py).
"""
import glob

import numpy as np
import pandas as pd

from scvi_pca import config

R = config.REPO
DS = [("mmrna", "RNA", "2.4M"), ("rna13m", "RNA", "13.8M"), ("mmatac", "ATAC", "0.6M"), ("covatac", "ATAC", "2.7M")]
SUB = {"all": "All cells", "tnk": "T + NK", "b": "B cells"}
NAME = {"rna": {"latent": "scVI stored latent", "pca": "PCA + Harmony", "retrain": "scVI retrain", "unintegrated": "uncorrected PCA"},
        "atac": {"latent": "PeakVI stored latent", "retrain": "PeakVI retrain", "unintegrated": "uncorrected LSI"}}
SCIB = ["scib:Bio conservation", "scib:Batch correction", "scib:Total", "scib:Isolated labels", "scib:KMeans NMI",
        "scib:KMeans ARI", "scib:Silhouette label", "scib:cLISI", "scib:BRAS", "scib:iLISI", "scib:KBET",
        "scib:Graph connectivity", "scib:PCR comparison"]


def md(df):
    cols = [str(c) for c in df.columns]
    fmt = lambda v: "—" if v is None or (isinstance(v, float) and np.isnan(v)) else (f"{v:.3f}" if isinstance(v, float) else str(v))
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] +
                     ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)])


def fmt_t(s):
    return "—" if pd.isna(s) else (f"{s / 60:.1f} min" if s >= 60 else f"{s:.1f} s")


def load():
    runs = pd.read_parquet(R / "results" / "runs.parquet")
    runs = runs[runs.status == "ok"]
    metrics = pd.concat([pd.read_parquet(f) for f in sorted(glob.glob(str(R / "results" / "metrics" / "*.parquet")))])
    setup = pd.read_parquet(R / "results" / "setup.parquet")
    return runs, metrics, setup


def runtime_table(runs, ds, names):
    d = runs[(runs.ds == ds) & (runs.rep == 2)]
    out = []
    for sub in SUB:
        s = d[d.subset == sub]
        if s.empty:
            continue
        row = {"selection": SUB[sub], "cells": f"{int(s.n_cells.iloc[0]):,}"}
        for k, n in names.items():
            if k != "unintegrated":
                v = s[s.strategy == k].t_e2e
                row[n] = fmt_t(v.iloc[0]) if len(v) else "—"
        out.append(row)
    return md(pd.DataFrame(out))


def quality_table(metrics, ds, names, level):
    m = metrics[metrics.ds == ds]
    out = []
    for sub in SUB:
        for k, n in names.items():
            s = m[(m.subset == sub) & (m.strategy == k)]
            if s.empty:
                continue
            row = {"selection": SUB[sub], "method": n}
            pur = s[s.metric == f"purity_macro_{level}"].value
            row["purity"] = float(pur.iloc[0]) if len(pur) else np.nan
            row["same-batch"] = float(s[s.metric == "same_batch"].value.iloc[0])
            for key in SCIB:
                v = s[(s.level == level) & (s.metric == key)].value
                row[key.replace("scib:", "")] = float(v.iloc[0]) if len(v) else np.nan
            out.append(row)
    return md(pd.DataFrame(out))


def main():
    runs, metrics, setup = load()
    parts = ["""# scvi_pca run 2: subset re-clustering benchmark

_Generated by `scripts/40_report.py`. Interactive charts: `report/compare_run2.html`
(published: https://claude.ai/artifact/G1VMrQLRQJ9kEpH9FirfXa). Overview: README.md._

App-style selections per dataset (all cells, T + NK, B cells, by L1 label), each re-embedded three ways for RNA
(stored scVI latent, PCA + Harmony via the dev_tools/rapids-benchmark steps, scVI retrained on the selection) and two
for ATAC (stored PeakVI latent, PeakVI retrained), then the same ivfflat neighbors → UMAP. Times are rep 2 of 2,
read → UMAP (`t_e2e`). Quality is scored on the same cells per selection (all labelled cells, or a sample-stratified
500k): kNN cell-type purity (k = 20, per-type mean), same-batch neighbour share (lower = more mixed), and the
scib-metrics Benchmarker standard sets, with total = 0.6 bio + 0.4 batch. The uncorrected embedding (PCA for RNA,
TF-IDF + LSI for ATAC) is the PCR reference and is listed for comparison.
"""]
    findings = (R / "report" / "compare_run2_findings.html")
    if findings.exists():
        import re
        text = re.sub(r"<h3>(.*?)</h3>", r"\n### \1\n", findings.read_text())
        text = re.sub(r"</?b>", "**", text)
        text = re.sub(r"<[^>]+>", "", text)
        parts.append("## Findings\n" + "\n".join(line.strip() for line in text.splitlines() if line.strip()).replace("### ", "\n### "))
    for ds, mod, size in DS:
        names = NAME[mod.lower()]
        su = setup[(setup.ds == ds) & (setup.rep == 1)]
        cost = f" Full-data model training (one-off): {fmt_t(float(su.t_pre_s.iloc[0]))}, {int(su.epochs.iloc[0])} epochs." if len(su) else ""
        parts.append(f"## {ds} ({mod}, {size} cells)\n\n### Re-cluster time\n{cost}\n\n{runtime_table(runs, ds, names)}")
        for level, lab in (("coarse", "coarse labels (AIFI_L2 / L2)"), ("fine", "fine labels (AIFI_L3 / L2.5)")):
            parts.append(f"### Quality, {lab}\n\n{quality_table(metrics, ds, names, level)}")
        parts.append(f"UMAPs: `umaps/aifi/{ds}/grid_subset_x_strategy.png` (rows = selection, columns = method), "
                     f"singles `umaps/aifi/{ds}/<method>/<selection>.png`, batch-coloured `umaps/batch/{ds}/<column>/`.")
    (R / "report" / "report.md").write_text("\n\n".join(parts) + "\n")
    print(f"wrote {R / 'report' / 'report.md'}")


if __name__ == "__main__":
    main()
